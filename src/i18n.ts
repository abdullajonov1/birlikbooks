export function matchFaq(text: string) {
  const value = text.toLowerCase()
  let best: 'hours' | 'delivery' | 'pay' | 'order' | null = null
  let score = 0
  for (const id of ['hours', 'delivery', 'pay', 'order'] as const) {
    const hits = faqWords[id].filter((word) => value.includes(word)).length
    if (hits > score) {
      score = hits
      best = id
    }
  }
  return best
}
